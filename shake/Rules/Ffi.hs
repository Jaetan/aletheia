-- | Extract the mangled MAlonzo name for a given Agda function from generated Haskell.
-- Looks for pattern: "d_<funcName>_XX ::"
extractMangledName :: String -> String -> Maybe String
extractMangledName funcName content =
    let prefix = "d_" ++ funcName ++ "_"
    in listToMaybe [name | line <- lines content,
                           funcName `isInfixOf` line,
                           "::" `isInfixOf` line,
                           let name = takeWhile (/= ' ') (dropWhile (== ' ') line),
                           prefix `isInfixOf` name]

-- | Extract the function name currently used in the FFI wrapper for a given Agda function.
-- Looks for pattern: "<qualifier>.d_<funcName>_XX" where qualifier is e.g. "AgdaJSON" or "AgdaBin".
extractFFIName :: String -> String -> String -> Maybe String
extractFFIName qualifier funcName content =
    let prefix = "d_" ++ funcName ++ "_"
        qualPrefix = qualifier ++ "." ++ prefix
        -- Text immediately following the first occurrence of `needle` in `s`
        -- (Nothing if absent).  Locating the qualifier prefix WITHIN the word —
        -- rather than assuming the word starts with it — makes extraction robust
        -- to surrounding punctuation: a paren-prefixed call `(AgdaX.d_f_12` or a
        -- backtick-wrapped mention in a comment both yield the same name.
        afterNeedle needle s
          | Just rest <- stripPrefix needle s = Just rest
          | (_ : t)   <- s                    = afterNeedle needle t
          | otherwise                         = Nothing
        -- Drop a Haskell `--` line comment before matching, so a mangled name
        -- merely MENTIONED in prose cannot satisfy the gate — only the actual
        -- wrapper call (code) counts.
        beforeComment s
          | "--" `isPrefixOf` s = ""
          | (c : cs) <- s       = c : beforeComment cs
          | otherwise           = ""
    in listToMaybe [ prefix ++ takeWhile isDigit rest
                   | line <- lines content,
                     let code = beforeComment line,
                     qualifier `isInfixOf` code,
                     funcName `isInfixOf` code,
                     name <- words code,
                     Just rest <- [afterNeedle qualPrefix name] ]

-- | Check that the FFI wrapper at `ffiFile` uses the correct mangled name for
-- a single function. A name that cannot be read on either side is an error,
-- not a warning: every `ffiExports` entry is a definition the wrapper calls,
-- so a wrapper that no longer calls one, or a MAlonzo module that no longer
-- defines one, is drift the gate exists to refuse.
checkOneFFIName :: FilePath -> String -> String -> String -> String -> Action ()
checkOneFFIName ffiFile qualifier funcName malonzoContent ffiContent =
    case (extractMangledName funcName malonzoContent, extractFFIName qualifier funcName ffiContent) of
        (Just generatedName, Just ffiName) ->
            when (generatedName /= ffiName) $ do
                putError $ unlines
                    [ ""
                    , "════════════════════════════════════════════════════════════════"
                    , "ERROR: MAlonzo function name mismatch for " ++ funcName ++ "!"
                    , "════════════════════════════════════════════════════════════════"
                    , ""
                    , "  Generated by Agda:  " ++ generatedName
                    , "  Currently in FFI:   " ++ ffiName
                    , ""
                    , "The Agda code structure changed, causing MAlonzo to generate"
                    , "a different mangled name. Update the FFI wrapper to match."
                    , ""
                    , "To fix, run:"
                    , "  sed -i 's/" ++ ffiName ++ "/" ++ generatedName ++ "/g' " ++ ffiFile
                    , ""
                    , "Then rebuild:"
                    , "  cabal run shake -- build"
                    , ""
                    , "════════════════════════════════════════════════════════════════"
                    , ""
                    ]
                error $ "FFI name mismatch for " ++ funcName ++ " - see above for fix instructions"
        (Nothing, _) ->
            error $ "FFI name check: no `d_" ++ funcName ++ "_<digits> ::` in the MAlonzo "
                 ++ "output; the Agda definition is gone or renamed"
        (_, Nothing) ->
            error $ "FFI name check: " ++ ffiFile ++ " has no call to " ++ qualifier
                 ++ ".d_" ++ funcName ++ "_<digits> outside a comment"

-- | The words of a generated data declaration `data T_<name>_<n> = …`, which
-- MAlonzo may spread over several indented lines; empty when it is absent.
dataDeclWords :: String -> String -> [String]
dataDeclWords name src =
    case break (("data T_" ++ name ++ "_") `isPrefixOf`) (lines src) of
      (_, decl : rest) -> concatMap words (decl : takeWhile (" " `isPrefixOf`) rest)
      _ -> []

-- | FFI export specification. Single source of truth for both
-- `checkFFINames` (verifies the FFI wrapper matches MAlonzo output, inline
-- in the Main.hs build rule and on demand via `check-ffi-names`) and
-- the `check-ffi-exports`/`regen-ffi-exports` phonies (maintain a
-- checked-in snapshot of mangled names to catch silent drift).
data FFIExport = FFIExport
    { ffiQualifier :: String  -- ^ the module's qualified-import alias in AletheiaFFI.hs
    , ffiFuncName  :: String  -- ^ function name as written in Agda
    , ffiModule    :: String  -- ^ MAlonzo output path relative to `build/MAlonzo/Code/`, no .hs suffix
    }

